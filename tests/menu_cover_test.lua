local cover = dofile(os.getenv("HOME") .. "/.config/sketchybar/plugins/menu_cover.lua")
local state = {}
assert(cover.update(state, 800, 1, 0) == 800)
assert(cover.update(state, 400, 2, 1) == 800, "keep old menu covered")
assert(cover.update(state, 400, 2, 1.2) == 800, "do not shrink during transition")
assert(cover.update(state, 400, 2, 1.5) == 400, "shrink after stable interval")
assert(cover.update(state, 900, 3, 1.6) == 900, "grow immediately")
assert(cover.update(state, 300, 4, 2) == 900)
assert(cover.update(state, 500, 5, 2.3) == 900, "rapid switch restarts settling")
assert(cover.update(state, 500, 5, 2.5) == 900)
assert(cover.update(state, 500, 5, 2.8) == 500)
assert(cover.update(state, 200, 6, 3) == 500)
assert(cover.update(state, 500, 5, 3.1) == 500)
assert(state.pending == nil, "returning to wider menu cancels shrink")
print("menu_cover: transition, rapid switch and cancellation checks passed")
